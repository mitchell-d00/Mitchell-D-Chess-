// Original KPK retrograde solver. No imported code, tablebase or neural weights.
// Canonical white pawn on files a-d, ranks 2-7, both kings, side to move.
const fs=require('node:fs'),E=require('./engine.cjs')();
const SIZE=24*64*64*2,valid=new Uint8Array(SIZE),win=new Uint8Array(SIZE),left=new Uint8Array(SIZE),queue=new Int32Array(SIZE);
const dist=(a,b)=>Math.max(Math.abs((a&7)-(b&7)),Math.abs((a>>3)-(b>>3)));
const attack=(p,b)=>(b>>3)===(p>>3)+1&&Math.abs((b&7)-(p&7))===1;
const index=(p,w,b,t)=>((((p&7)*6+(p>>3)-1)*64+w)*64+b)*2+t;
const good=(p,w,b,t)=>w!==p&&b!==p&&dist(w,b)>1&&(t===1||!attack(p,b));
const near=Array.from({length:64},(_,s)=>Array.from({length:64},(_,t)=>t).filter(t=>dist(s,t)===1));
function promotion(p,w,b){
 // Q/R conversion is won unless the defender can capture immediately or is stalemated.
 for(const piece of ['Q','R']){
  const board=Array(64).fill('');board[w]='K';board[b]='k';board[p+8]=piece;
  let fen='';for(let rank=7;rank>=0;rank--){let empty=0;for(let f=0;f<8;f++){const v=board[rank*8+f];if(!v){empty++;continue;}if(empty){fen+=empty;empty=0;}fen+=v;}if(empty)fen+=empty;if(rank)fen+='/';}
  const pos=new E.Chess(fen+' b - - 0 1'),moves=pos.legalMoves();
  if(!moves.length){if(pos.inCheck())return true;continue;}
  const target=((p+8)>>3)*16+(p&7);
  if(!moves.some(m=>E.mTo(m)===target))return true;
 }
 return false;
}
let tail=0,legal=0;
for(let f=0;f<4;f++)for(let r=1;r<7;r++)for(let w=0;w<64;w++)for(let b=0;b<64;b++)for(let t=0;t<2;t++){
 const p=r*8+f,i=index(p,w,b,t);if(!good(p,w,b,t))continue;valid[i]=1;legal++;
 let count=0,won=false;
 if(t===0){
  for(const k of near[w])if(k!==p&&dist(k,b)>1)count++;
  if(p+8!==w&&p+8!==b){if(r===6)won=promotion(p,w,b);else {count++;if(r===1&&p+16!==w&&p+16!==b)count++;}}
 }else{
  for(const k of near[b])if(dist(k,w)>1&&(k===p||!attack(p,k)))count++;
  if(count===0&&attack(p,b))won=true;
 }
 left[i]=count;if(won){win[i]=1;queue[tail++]=i;}
}
let head=0;
function visit(i){if(!valid[i]||win[i])return;if((i&1)===0||--left[i]===0){win[i]=1;queue[tail++]=i;}}
while(head<tail){
 let n=queue[head++],t=n&1;n>>=1;const b=n&63;n>>=6;const w=n&63;n>>=6;const p=((n%6+1)<<3)+(n/6|0);
 if(t===1){
  for(const k of near[w])visit(index(p,k,b,0));
  if((p>>3)>1)visit(index(p-8,w,b,0));
  if((p>>3)===3&&p-8!==w&&p-8!==b)visit(index(p-16,w,b,0));
 }else for(const k of near[b])visit(index(p,w,k,1));
}
const bits=Buffer.alloc(SIZE/8);for(let i=0;i<SIZE;i++)if(win[i])bits[i>>3]|=1<<(i&7);
let html=fs.readFileSync('index.html','utf8');
const block=`  // Generated by scripts/build-kpk.cjs: exact KPK wins, all other legal states draw.\n  var KPK_DATA = '${bits.toString('base64')}';\n`;
if(html.includes('  var KPK_DATA ='))html=html.replace(/  \/\/ Generated by scripts\/build-kpk.cjs[^\n]*\n  var KPK_DATA = '[^']*';\n/,block);
else html=html.replace('  // ---------- Evaluation ----------',block+'\n  // ---------- Evaluation ----------');
fs.writeFileSync('index.html',html);console.log(JSON.stringify({legal,winning:tail,bytes:bits.length}));
